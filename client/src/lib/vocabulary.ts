// Cards are study-ready unless audioReady is false. Every imported card ships
// with its ElevenLabs clips in public/audio/index.json.
const cardKey = (card: VocabularyCard) =>
  `${card.front}::${card.back.trim().toLocaleLowerCase()}`;

export const CURATED_CARDS: VocabularyCard[] = CURATED_VOCABULARY_DATA.map(
  card => ({
    ...card,
    source: card.source ?? "Goyo curated",
    audioReady: card.audioReady ?? true,
  })
);

export const CURATED_STUDY_READY = CURATED_CARDS.filter(
  card => card.audioReady !== false
);

export interface VocabularyDeck {
  vocabulary: VocabularyCard[];
  studyReady: VocabularyCard[];
}

let deckPromise: Promise<VocabularyDeck> | null = null;

/**
 * The curated deck ships with the app; the imported Essential 600 deck is a
 * separate chunk loaded after first paint so the initial bundle stays small.
 */
export function loadVocabularyDeck(): Promise<VocabularyDeck> {
  if (!deckPromise) {
    deckPromise = import("./essentialVocabulary").then(
      ({ ESSENTIAL_WORDS }) => {
        const curatedCards = new Set(CURATED_CARDS.map(cardKey));
        const vocabulary = [
          ...CURATED_CARDS,
          ...ESSENTIAL_WORDS.filter(card => !curatedCards.has(cardKey(card))),
        ];
        return {
          vocabulary,
          studyReady: vocabulary.filter(card => card.audioReady !== false),
        };
      }
    );
  }
  return deckPromise;
}
